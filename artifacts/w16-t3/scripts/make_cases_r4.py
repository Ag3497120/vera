C = []


def case(id_, type_, doc, question, answer, quotes, expect, reason, note):
    lines = doc if isinstance(doc, list) else [doc]
    body = "\n".join(lines)
    qs = [{"source": "doc.txt", "line": ln, "text": t} for ln, t in quotes]
    C.append({"id": id_, "type": type_, "docs": {"doc.txt": body}, "question": question, "answer": answer,
              "quotes": qs, "expect": expect, "expect_reason_prefix": reason, "note": note})


