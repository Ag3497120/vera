def _path(fn):
    p = os.path.join(DATA, "docs", fn)
    return p if os.path.exists(p) else os.path.join(DATA, "docs_unrelated", fn)


_cache = {}


def lines_of(key):
    fn = FN[key]
    if fn not in _cache:
        with open(_path(fn), encoding="utf-8") as f:
            _cache[fn] = f.read().splitlines()
    return _cache[fn]


def L(key, anchor):
    hits = [i + 1 for i, t in enumerate(lines_of(key)) if anchor in t]
    if len(hits) != 1:
        raise SystemExit("anchor %r in %s matched lines %r" % (anchor, key, hits))
    return {"doc": FN[key], "line": hits[0]}


def D(value, key, anchor):
    r = L(key, anchor)
    if unicodedata.normalize("NFKC", value) not in unicodedata.normalize("NFKC", lines_of(key)[r["line"] - 1]):
        raise SystemExit("distractor %r not in %s:%d" % (value, key, r["line"]))
    return {"value": value, "doc": r["doc"], "line": r["line"]}


